DEFAULT_USERS = [
    ("user", "user@example.com", "user123", "user"),
    ("creator", "creator@example.com", "creator123", "creator"),
    ("admin", "admin@example.com", "admin123", "admin")
]

def create_database_tables(connection_string: str) -> bool:
    if not psycopg2:
        print("Error: psycopg2-binary is not installed. Please run: pip install psycopg2-binary")
        return False

    print("Connecting to Supabase PostgreSQL database...")
    try:
        conn = psycopg2.connect(connection_string)
        conn.autocommit = True
        cursor = conn.cursor()

        print("Executing table creation queries...")
        for query in TABLE_QUERIES:
            cursor.execute(query)

        print("Verifying default users...")
        insert_user_sql = """
        INSERT INTO users_ci (username, email, password_hash, role)
        VALUES (%s, %s, %s, %s)
        ON CONFLICT (username) DO NOTHING;
        """
        for uname, email, pwd, role in DEFAULT_USERS:
            cursor.execute(insert_user_sql, (uname, email, hash_password(pwd), role))

        cursor.close()
        conn.close()
        print("All tables and security configurations created successfully in Supabase.")
        return True
    except Exception as e:
        print(f"Database connection error: {e}")
        return False

def main():
    conn_str = get_connection_string()
    if not conn_str:
        if sys.stdin.isatty():
            try:
                entered = input("Enter Supabase PostgreSQL connection string (postgresql://postgres:[password]@db.[ref].supabase.co:5432/postgres): ").strip()
                if entered:
                    conn_str = entered
            except EOFError:
                pass

    if not conn_str:
        print("Error: PostgreSQL connection string not provided.")
        print("Usage:")
        print("  python databasecreator.py postgresql://postgres:[password]@db.[ref].supabase.co:5432/postgres")
        print("Or set DATABASE_URL in your .env file:")
        print("  DATABASE_URL=postgresql://postgres:[password]@db.[ref].supabase.co:5432/postgres")
        sys.exit(1)

    success = create_database_tables(conn_str)
    if not success:
        sys.exit(1)

if __name__ == "__main__":
    main()
