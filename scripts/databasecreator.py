import sys
import os
import re
import hashlib
from dotenv import load_dotenv

SCRIPTS_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.dirname(SCRIPTS_DIR)
load_dotenv(os.path.join(ROOT_DIR, ".env"))
load_dotenv()

try:
    import psycopg2
    from psycopg2 import sql
except ImportError:
    psycopg2 = None

def hash_password(password: str) -> str:
    return hashlib.sha256(password.encode("utf-8")).hexdigest()

def extract_project_ref(url: str) -> str:
    if not url:
        return ""
    match = re.search(r"https?://([^.]+)\.supabase\.co", url)
    if match:
        return match.group(1)
    return ""

def get_connection_string() -> str:
    for arg in sys.argv[1:]:
        if arg.startswith("postgresql://") or arg.startswith("postgres://"):
            return arg
        if arg.startswith("--url="):
            return arg.split("=", 1)[1]

    direct_url = os.getenv("DATABASE_URL", "").strip()
    if direct_url:
        return direct_url

    supabase_db_url = os.getenv("SUPABASE_DB_URL", "").strip()
    if supabase_db_url:
        return supabase_db_url

    password = os.getenv("SUPABASE_DB_PASSWORD", "").strip() or os.getenv("SUPABASE_PASSWORD", "").strip() or os.getenv("DB_PASSWORD", "").strip()
    supabase_url = os.getenv("SUPABASE_URL", "").strip()
    ref = extract_project_ref(supabase_url)

    if password and ref:
        return f"postgresql://postgres:{password}@db.{ref}.supabase.co:5432/postgres"

    return ""

